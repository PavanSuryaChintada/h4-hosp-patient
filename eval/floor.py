"""The floor and ceiling on all 1,500 training patients, scored by the official scorer.

    python -m eval.floor

Runs the organisers' baseline, the oracle, and each through our minor-alert policy, scores them
with the unmodified ``evaluate.py`` against train_labels.csv, and writes ``eval/floor.json`` and
``docs/baseline-floor.md``. Both are committed: the pack baseline's score is the floor every
later change is read against, and the with/without-minor pairs are the measurement behind
EMIT_MINOR (docs/DECISIONS.md D-018).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from eval.baselines import score_references
from eval.pack import ROOT, data_dir, require_pack
from eval.run import WORK_DIR, _num, _relative, _table, data_version, git_revision
from eval.split import split_ids
from eval.truth import write_truth_subset
from medsafe.data.adapter import load_dataset

FLOOR_JSON = ROOT / "eval" / "floor.json"
DOCS_PATH = ROOT / "docs" / "baseline-floor.md"
COMPONENTS = ("serious_recall", "near_miss_serious_recall", "precision_all",
              "graded_recall_non_minor", "resolution_accuracy", "noise_alerts_per_patient",
              "alert_fatigue_multiplier")


def render_markdown(references: dict[str, dict[str, Any]]) -> str:
    """docs/baseline-floor.md from the reference reports."""
    def delta(with_minor: str, without: str) -> str:
        """Primary-score change from dropping minor alerts, signed."""
        change = references[without]["primary_score"] - references[with_minor]["primary_score"]
        return f"{change:+.4f}"

    return "\n\n".join([
        "# Floor and ceiling",
        f"Generated by `python -m eval.floor` at `{git_revision()}` (data version "
        f"`{data_version(data_dir())}`). Do not edit by hand. All 1,500 training patients, "
        f"scored by the organisers' unmodified `evaluate.py`.",
        _table(["Reference", "**Primary**", *COMPONENTS],
               [[name, f"**{r['primary_score']:.4f}**",
                 *[_num(r["components"][c]) for c in COMPONENTS]]
                for name, r in references.items()]),
        "## Minor alerts, measured both ways",
        _table(["Detector", "With minor alerts", "Without", "Change"],
               [["oracle (perfect detection)", f"{references['oracle']['primary_score']:.4f}",
                 f"{references['oracle, no minor']['primary_score']:.4f}",
                 delta("oracle", "oracle, no minor")],
                ["pack baseline (weak detection)",
                 f"{references['pack baseline']['primary_score']:.4f}",
                 f"{references['pack baseline, no minor']['primary_score']:.4f}",
                 delta("pack baseline", "pack baseline, no minor")]]),
        "Minor alerts drive alert fatigue, fatigue drives dismissal, and dismissal buries the "
        "serious alert, so the predictions file leaves them out (EMIT_MINOR = False, "
        "src/medsafe/output/policy.py); the clinician view still shows them, ranked last. The "
        "measurement above corroborates it for both a perfect and a weak detector.",
    ]) + "\n"


def main() -> int:
    """Command-line entry point. Returns 0, or 2 if the pack or scorer is missing."""
    try:
        require_pack()
        ids = split_ids((p.patient_id for p in load_dataset(data_dir(), "train").patients), "train")
        folder = WORK_DIR / "floor"
        labels, truth_resolution = write_truth_subset(data_dir(), ids, folder / "truth")
        references = score_references(data_dir(), ids, labels, truth_resolution, folder / "references")
    except FileNotFoundError as error:
        print(f"cannot score: {error}", file=sys.stderr)
        return 2
    summary = {name: {"primary_score": r["primary_score"], "components": r["components"]}
               for name, r in references.items()}
    FLOOR_JSON.write_text(json.dumps({"git_revision": git_revision(),
                                      "data_version": data_version(data_dir()),
                                      "references": summary}, indent=2) + "\n", encoding="utf-8")
    DOCS_PATH.write_text(render_markdown(references), encoding="utf-8")
    for name, r in references.items():
        c = r["components"]
        print(f"{name:<26} primary {r['primary_score']:.4f}  serious {c['serious_recall']:.4f}  "
              f"near-miss {c['near_miss_serious_recall']:.4f}  precision {c['precision_all']:.4f}  "
              f"graded {c['graded_recall_non_minor']:.4f}  resolution {c['resolution_accuracy']:.4f}"
              f"  noise {c['noise_alerts_per_patient']:.4f}")
    print(f"wrote {_relative(FLOOR_JSON)} and {_relative(DOCS_PATH)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
