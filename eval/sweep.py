"""Threshold sweep: find the ridge between recall and alert volume deliberately, not by luck.

    python -m eval.sweep [--input tests/fixtures] [--docs docs/sweep.md]

Runs the pipeline at every ALERT_CAP in 2-8 and MIN_CONFIDENCE in 0.60-0.90, reports both
headline numbers and the mirror score at each setting, prints the best setting, and writes the
full table to docs/sweep.md. If every setting scores the same, it says so instead of naming a
winner: a flat table means no built stage reads these thresholds yet.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

from eval.run import DEFAULT_INPUT, ROOT, _display, _num, _table, data_version, evaluate, git_revision
from eval.truth import Truth, load_truth
from medsafe.data.adapter import Dataset, load_dataset
from medsafe.pipeline import Settings

ALERT_CAPS = tuple(range(2, 9))
MIN_CONFIDENCES = (0.60, 0.65, 0.70, 0.75, 0.80, 0.85, 0.90)
DEFAULT_DOCS = ROOT / "docs" / "sweep.md"


def sweep(dataset: Dataset, truth: Truth) -> list[dict[str, Any]]:
    """Score every (alert cap, minimum confidence) setting. One row per setting, in sweep order."""
    rows = []
    for cap in ALERT_CAPS:
        for confidence in MIN_CONFIDENCES:
            result = evaluate(dataset, truth, Settings(alert_cap=cap, min_confidence=confidence),
                              with_baselines=False)
            m = result.metrics
            rows.append({"alert_cap": cap, "min_confidence": confidence,
                         "serious_recall": m["serious_recall"],
                         "near_miss_recall": m["near_miss_recall"],
                         "alerts_before": m["alerts_per_patient_before"],
                         "alerts_after": m["alerts_per_patient_after"],
                         "score": result.score})
    return rows


def best(rows: list[dict[str, Any]]) -> dict[str, Any]:
    """The highest-scoring setting. Ties go to fewer alerts, then a smaller cap, then a
    stricter minimum confidence. Deterministic."""
    return max(rows, key=lambda r: (round(r["score"], 9), -round(r["alerts_after"], 9),
                                    -r["alert_cap"], r["min_confidence"]))


def is_flat(rows: list[dict[str, Any]]) -> bool:
    """True if every setting gives the same score, recall and alert volume."""
    keys = ("score", "serious_recall", "alerts_after")
    return len({tuple(row[k] for k in keys) for row in rows}) == 1


def render_markdown(rows: list[dict[str, Any]], input_dir: Path) -> str:
    """docs/sweep.md: provenance, the verdict, a score grid, and the full table."""
    winner = best(rows)
    if is_flat(rows):
        verdict = (f"**Flat: every setting scores {winner['score']:.3f}.** No built stage reads "
                   f"these thresholds yet (MIN_CONFIDENCE is read by Phase 2, ALERT_CAP by "
                   f"Phase 6), so there is no ridge to find. Re-run after those phases land.")
    else:
        verdict = (f"**Best: ALERT_CAP {winner['alert_cap']}, MIN_CONFIDENCE "
                   f"{winner['min_confidence']:.2f}**, mirror score {winner['score']:.3f}, "
                   f"serious recall {_num(winner['serious_recall'])}, "
                   f"{winner['alerts_after']:.1f} alerts per patient.")
    grid = _table(["ALERT_CAP \\ MIN_CONFIDENCE"] + [f"{c:.2f}" for c in MIN_CONFIDENCES],
                  [[cap] + [f"{r['score']:.3f}" for r in rows if r["alert_cap"] == cap]
                   for cap in ALERT_CAPS])
    full = _table(["ALERT_CAP", "MIN_CONFIDENCE", "Serious recall", "Near-miss recall",
                   "Alerts/patient before", "Alerts/patient after", "Mirror score"],
                  [[r["alert_cap"], f"{r['min_confidence']:.2f}", _num(r["serious_recall"]),
                    _num(r["near_miss_recall"]), f"{r['alerts_before']:.1f}",
                    f"{r['alerts_after']:.1f}", f"{r['score']:.3f}"] for r in rows])
    return "\n\n".join([
        "# Threshold sweep",
        f"Generated by `python -m eval.sweep` at `{git_revision()}` on `{_display(input_dir)}` "
        f"(data version `{data_version(input_dir)}`). Do not edit by hand.",
        verdict,
        "## Mirror score by setting", grid,
        "## Every setting", full,
    ]) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Command-line entry point. Returns 0, or 2 if the input has no labels."""
    parser = argparse.ArgumentParser(description="Sweep ALERT_CAP and MIN_CONFIDENCE.")
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--docs", type=Path, default=DEFAULT_DOCS)
    args = parser.parse_args(argv)

    truth = load_truth(args.input)
    if truth is None:
        print(f"no labels in {args.input}: nothing to sweep against", file=sys.stderr)
        return 2
    rows = sweep(load_dataset(args.input), truth)
    args.docs.parent.mkdir(parents=True, exist_ok=True)
    args.docs.write_text(render_markdown(rows, args.input), encoding="utf-8")

    print(f"{'cap':>4}{'min_conf':>10}{'recall':>8}{'alerts/pt':>11}{'score':>8}")
    for r in rows:
        print(f"{r['alert_cap']:>4}{r['min_confidence']:>10.2f}{_num(r['serious_recall']):>8}"
              f"{r['alerts_after']:>11.1f}{r['score']:>8.3f}")
    winner = best(rows)
    if is_flat(rows):
        print(f"\nflat: every setting scores {winner['score']:.3f}; no built stage reads these "
              f"thresholds yet")
    else:
        print(f"\nbest: ALERT_CAP {winner['alert_cap']}, MIN_CONFIDENCE "
              f"{winner['min_confidence']:.2f} -> score {winner['score']:.3f}")
    print(f"table: {_display(args.docs)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
